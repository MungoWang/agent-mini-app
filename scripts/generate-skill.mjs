#!/usr/bin/env node
/**
 * Extract component contracts from @monkey-mini-app/ui source (TS AST + JSDoc)
 * and write packages/dsh/skills/monkey-mini-app/references/{catalog.md,contracts/*.md}
 * plus packages/ui/ai/catalog.json
 *
 * Each contract includes:
 *   - component props (expanded)
 *   - referenced / co-exported types with field tables
 *     (e.g. ActivityFeed → TimelineItem { id, title, … })
 *
 * Annotate components with:
 *   /** summary
 *    *  @when when to pick this
 *    *  @example <Foo />
 *    * /
 *
 * Usage: pnpm skill:gen
 */
import fs from "node:fs"
import path from "node:path"
