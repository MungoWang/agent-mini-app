/**
 * Read the portable examples package (packages/ui-examples) and publish it into
 * the skill: `references/examples/<component>/<name>-NN.tsx`, plus one index doc
 * per `@group`. Contracts link the files and quote `@title` + `@scenario`, so an
 * agent picks the right example from the catalog page and opens the source only
 * for the one it chose (keeps the 8 KB contract cap honest).
 *
 * Metadata is the JSDoc header of each example file — that, not the folder name,
 * is what ties an example to a component:
 *
 *   @exampleOf DataGrid   subject component (mutually exclusive with @group)
 *   @group forms          collaborative/layout demo, no single subject
 *   @title  …             what this example shows
 *   @scenario …           the situation it represents (distinct from siblings)
 *   @hint …               optional gotcha / detail
 */
import fs from "node:fs"
import path from "node:path"

const TAG = /@(exampleOf|group|title|scenario|hint)\s+(.*)/g

function readMeta(src) {
  const block = /^\/\*\*([\s\S]*?)\*\//.exec(src)
  const meta = { exampleOf: "", group: "", title: "", scenario: "", hint: "" }
  if (!block) return meta
  for (const m of block[1].matchAll(TAG)) {
    const key = m[1] === "exampleOf" ? "exampleOf" : m[1]
    meta[key] = m[2].trim()
  }
  return meta
}

function walkTs(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name)
    if (ent.isDirectory()) walkTs(full, out)
    else if (ent.name.endsWith(".tsx")) out.push(full)
  }
  return out
}

/**
 * Parse every example under packages/ui-examples/src.
 * `src/components/<dir>/…` → published at `references/examples/<dir>/…`
 * Looks live under `src/looks/` and are **not** copied here — `looks.mjs` writes markdown specs.
 */
export function loadExamples(examplesRoot) {
  const out = []
  for (const f of walkTs(path.join(examplesRoot, "src/components"))) {
    const src = fs.readFileSync(f, "utf8")
    out.push({ file: f, dir: path.basename(path.dirname(f)), base: path.basename(f), src, ...readMeta(src) })
  }
  return out
}

/**
 * Copy examples (+ their shared helpers) into the skill and build the
 * subject → examples index used by render.mjs.
 */
export function writeSkillExamples({ skillRef, examples, sharedRoot, subjectSlugs, examplesRoot }) {
  const outRoot = path.join(skillRef, "examples")
  fs.rmSync(outRoot, { recursive: true, force: true })
  fs.mkdirSync(outRoot, { recursive: true })

  const bySubject = new Map() // component name → [{ href, title, scenario }]
  const byGroup = new Map() // group slug → [example]
  const missingSubject = []

  for (const ex of examples) {
    // ../../shared/x → ../shared/x once it lives at references/examples/<dir>/
    const code = ex.src.replace(/(["'])\.\.\/\.\.\/shared\//g, "$1../shared/")
    const dest = path.join(outRoot, ex.dir, ex.base)
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, code)
    const href = `${ex.dir}/${ex.base}`
    const entry = {
      href,
      base: ex.base,
      title: ex.title || ex.base.replace(/\.tsx$/, ""),
      scenario: ex.scenario,
      hint: ex.hint,
    }

    if (ex.exampleOf) {
      const list = bySubject.get(ex.exampleOf) ?? []
      list.push(entry)
      bySubject.set(ex.exampleOf, list)
      if (subjectSlugs && !subjectSlugs.has(ex.exampleOf)) missingSubject.push(`${ex.exampleOf} (${ex.dir}/${ex.base})`)
    } else {
      const key = ex.group || "misc"
      const list = byGroup.get(key) ?? []
      list.push(entry)
      byGroup.set(key, list)
    }
  }

  // shared sample data / helpers the copied files import
  if (sharedRoot && fs.existsSync(sharedRoot)) {
    const dest = path.join(outRoot, "shared")
    fs.mkdirSync(dest, { recursive: true })
    for (const f of fs.readdirSync(sharedRoot)) {
      if (f === "example.tsx") continue // <Example> gallery chrome — not part of an example
      if (f.endsWith(".ts") || f.endsWith(".tsx")) fs.copyFileSync(path.join(sharedRoot, f), path.join(dest, f))
    }
  }

  for (const [group, list] of byGroup) {
    const lines = [
      "<!-- generated by scripts/gen/skill — do not edit -->",
      "",
      `# Examples · ${group}`,
      "",
      "Multi-component demos: layout/pattern recipes with no single subject component.",
      "Copy the whole file into `ui.tsx` (or split it) — imports are `react` + `@monkey-mini-app/ui` only.",
      "",
      "| example | what it shows | scenario |",
      "|---|---|---|",
    ]
    for (const e of list) lines.push(`| [\`${e.base}\`](./${e.href}) | ${e.title} | ${e.scenario} |`)
    lines.push("")
    fs.writeFileSync(path.join(outRoot, `${group}.md`), lines.join("\n"))
  }

  return { bySubject, byGroup, missingSubject }
}
