#!/usr/bin/env node
/**
 * Share the ui-examples package with the dsh e2e fixture app (`com.example.kit`).
 *
 * The examples are written to be mini-app-portable (react + bare @monkey-mini-app/ui +
 * relatives), so publishing them here is a **byte copy** — only the `../../shared/…`
 * helper path is rewritten. That is the point: the same source the gallery shows and
 * the skill teaches is what the fixture actually compiles and runs in a browser.
 *
 * Inputs:       packages/ui-examples/src/{areas,components,shared}
 * Writes:       apps/dsh-host/fixtures/com.example.kit/lib/examples/**
 *               apps/dsh-host/fixtures/com.example.kit/lib/sections.tsx
 * Side effects: repo tracked files — commit the regenerated diff (CI asserts freshness)
 * Run as:       pnpm gen:examples (also part of pnpm verify)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const exRoot = path.join(repoRoot, "packages/ui-examples/src");
const fixture = path.join(repoRoot, "apps/dsh-host/fixtures/com.example.kit");
const outExamples = path.join(fixture, "lib/examples");
const outFile = path.join(fixture, "lib/sections.tsx");

const BANNER = `// generated by scripts/gen/examples.mjs — do not edit (runs from packages/ui-examples)`;

/** nav copy is product copy: it follows the shipped host locale (zh), like the templates */
const SECTIONS = [
  { area: "primitives", id: "primitives", label: "基础元素", hint: "原子与容器" },
  { area: "overlays", id: "overlays", label: "浮层", hint: "弹窗与提示" },
  { area: "forms", id: "forms", label: "表单", hint: "输入与选择" },
  { area: "dates", id: "dates", label: "日期时间", hint: "日历与时长" },
  { area: "data", id: "data", label: "数据", hint: "表格与列表" },
  { area: "editors", id: "editors", label: "编辑器", hint: "代码与文档" },
  { area: "products", id: "products", label: "看板日历", hint: "流程与排期" },
  { area: "charts-blocks", id: "charts", label: "图表指标", hint: "可视化" },
];

const TAG = /@(exampleOf|group|title|scenario|hint)\s+(.*)/g;

function metaOf(src) {
  const block = /^\/\*\*([\s\S]*?)\*\//.exec(src);
  const m = { exampleOf: "", group: "", title: "", scenario: "", hint: "" };
  if (!block) return m;
  for (const t of block[1].matchAll(TAG)) {
    const k = t[1] === "exampleOf" ? "exampleOf" : t[1];
    m[k] = t[2].trim();
  }
  return m;
}

/** area slug → the example files it composes, in render order (with chrome attrs) */
function readArea(area) {
  const src = fs.readFileSync(path.join(exRoot, "areas", `${area}.tsx`), "utf8");
  const importRe = /import (\w+) from "\.\.\/components\/([^/"]+)\/([^"]+)"/g;
  const byName = new Map();
  for (const m of src.matchAll(importRe)) byName.set(m[1], { dir: m[2], base: m[3] });

  const out = [];
  const blockRe = /<Example\b([^>]*)>\s*<(\w+) \/>\s*<\/Example>/gs;
  for (const m of src.matchAll(blockRe)) {
    const attrs = {};
    for (const a of m[1].matchAll(/(id|title|hint)="([^"]*)"/g)) attrs[a[1]] = a[2];
    const imp = byName.get(m[2]);
    if (!imp) throw new Error(`${area}.tsx: no import for ${m[2]}`);
    out.push({ ...imp, exportName: m[2], attrs });
  }
  return out;
}

function portable(src) {
  return src.replace(/(["'])\.\.\/\.\.\/shared\//g, "$1../shared/");
}

// ---------------------------------------------------------------- copy examples
fs.rmSync(outExamples, { recursive: true, force: true });
fs.mkdirSync(path.join(outExamples, "shared"), { recursive: true });

const copied = new Map(); // "<dir>/<base>" → meta
const groups = [];

for (const sec of SECTIONS) {
  const units = readArea(sec.area);
  groups.push({ ...sec, units });
  for (const u of units) {
    const from = path.join(exRoot, "components", u.dir, `${u.base}.tsx`);
    if (!fs.existsSync(from)) throw new Error(`missing example source: ${from}`);
    const src = fs.readFileSync(from, "utf8");
    fs.mkdirSync(path.join(outExamples, u.dir), { recursive: true });
    fs.writeFileSync(path.join(outExamples, u.dir, `${u.base}.tsx`), portable(src));
    copied.set(`${u.dir}/${u.base}`, metaOf(src));
  }
}

for (const f of fs.readdirSync(path.join(exRoot, "shared"))) {
  if (!/\.(ts|tsx)$/.test(f)) continue;
  fs.copyFileSync(path.join(exRoot, "shared", f), path.join(outExamples, "shared", f));
}

// ---------------------------------------------------------------- sections.tsx
const lines = [BANNER, "", 'import { Example } from "./examples/shared/example";', ""];

const importNames = new Set();
for (const g of groups) {
  for (const u of g.units) {
    if (importNames.has(u.exportName)) throw new Error(`duplicate example export ${u.exportName}`);
    importNames.add(u.exportName);
    lines.push(`import ${u.exportName} from "./examples/${u.dir}/${u.base}";`);
  }
}
lines.push("");
lines.push(`export type SectionId = ${groups.map((g) => `"${g.id}"`).join(" | ")};`);
lines.push("");
lines.push("export const SECTIONS: { id: SectionId; label: string; hint: string }[] = [");
for (const g of groups) lines.push(`  { id: "${g.id}", label: "${g.label}", hint: "${g.hint}" },`);
lines.push("];");
lines.push("");
lines.push("/** One <Example> chrome block per shared example, in gallery order. */");
lines.push("export const SECTION_BODIES: Record<SectionId, () => JSX.Element> = {");
for (const g of groups) {
  lines.push(`  ${g.id}: () => (`);
  lines.push("    <>");
  for (const u of g.units) {
    const attrs = ["id", "title", "hint"].filter((k) => u.attrs[k]).map((k) => `${k}="${u.attrs[k]}"`);
    lines.push(`      <Example ${attrs.join(" ")}>`);
    lines.push(`        <${u.exportName} />`);
    lines.push("      </Example>");
  }
  lines.push("    </>");
  lines.push("  ),");
}
lines.push("};");
lines.push("");
fs.writeFileSync(outFile, lines.join("\n"));

const n = [...copied.keys()].length;
console.log(`gen:examples — ${n} examples + ${fs.readdirSync(path.join(exRoot, "shared")).length} shared files → ${path.relative(repoRoot, outExamples)}`);
console.log(`gen:examples — ${groups.length} sections → ${path.relative(repoRoot, outFile)}`);
